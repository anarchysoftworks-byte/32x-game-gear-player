/*
 * z80_compute_daa — Inline DAA (Decimal Adjust Accumulator)
 *
 * Replaces the 4 KB DAATable with ~20 lines of arithmetic.
 * Algorithm verified against MAME z80.cpp and all 2048 DAATable entries.
 * Input:  a = accumulator, f = flags register
 * Output: packed AF word (A in high byte, F in low byte)
 */
static inline uint16_t z80_compute_daa(uint8_t a, uint8_t f)
{
    uint8_t old_a = a;
    uint8_t correction = 0;
    uint8_t new_c = (f & C_FLAG);           /* C is sticky (never cleared) */

    if ((a & 0x0F) > 0x09 || (f & H_FLAG))
        correction |= 0x06;
    if (a > 0x99 || (f & C_FLAG)) {
        correction |= 0x60;
        new_c = C_FLAG;
    }

    if (f & N_FLAG)
        a -= correction;                    /* subtract path */
    else
        a += correction;                    /* add path (common) */

    f = PZSTable[a]                         /* S, Z, P from 256-byte table */
      | (a & 0x28)                          /* undocumented Y (bit5), X (bit3) */
      | (f & N_FLAG)                        /* preserve N */
      | new_c                               /* C = old_C | (old_A > 0x99) */
      | ((old_a ^ a) & H_FLAG);            /* H = half-carry of correction */

    return ((uint16_t)a << 8) | f;
}

